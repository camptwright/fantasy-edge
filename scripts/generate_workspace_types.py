"""Generate preview response types from Pydantic's API schemas; --check in CI."""
import argparse
import json
from pathlib import Path

from src.api.routers.workspace import EngineQualification, Leagues, Overview, Recap, StandingsView, TradeIdeas, TradeResult

TARGET = Path(__file__).resolve().parents[1] / 'dashboard/src/lib/workspace-api.generated.ts'


def ts_type(schema):
    if '$ref' in schema:
        return schema['$ref'].rsplit('/', 1)[-1]
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(ts_type(value) for value in schema['anyOf'])
    kind = schema.get('type')
    if kind == 'array':
        return f"Array<{ts_type(schema['items'])}>"
    if kind == 'object' and isinstance(schema.get('additionalProperties'), dict) and not schema.get('properties'):
        return f"Record<string, {ts_type(schema['additionalProperties'])}>"
    if kind == 'object':
        # Response defaults are always serialized (not exclude_unset).
        return '{\n' + ''.join(f"  {key}: {ts_type(value)};\n" for key, value in
                               schema.get('properties', {}).items()) + '}'
    if kind in ('string', 'boolean', 'null'):
        return kind
    if kind in ('number', 'integer'):
        return 'number'
    raise ValueError(f'Unsupported API schema: {schema}')


def render():
    schemas = {}
    for model in (EngineQualification, Leagues, Overview, Recap, StandingsView, TradeIdeas, TradeResult):
        schema = model.model_json_schema(mode='serialization')
        schemas.update(schema.pop('$defs', {}))
        schemas[model.__name__] = schema
    return '// Generated by scripts/generate_workspace_types.py; do not edit.\n' + '\n'.join(
        f'export type {name} = {ts_type(schema)};\n' for name, schema in sorted(schemas.items()))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != content:
            raise SystemExit('Workspace API types are out of date; regenerate them.')
    else:
        TARGET.write_text(content)
